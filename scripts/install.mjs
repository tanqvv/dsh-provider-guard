/** @param {string[]} argv */
function parseArgs(argv) {
  const options = {
    apply: false,
    uninstall: false,
    noCopy: false,
    bundle: false,
    dryRun: false,
    dshHome: process.env.DSH_HOME?.trim() || join(homedir(), '.dsh'),
    profiles: [],
    mode: 'enforce',
  }
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i]
    const [flag, inline] = arg.includes('=') ? [arg.slice(0, arg.indexOf('=')), arg.slice(arg.indexOf('=') + 1)] : [arg, undefined]
    const value = () => inline ?? argv[++i]
    if (flag === '--apply') options.apply = true
    else if (flag === '--dry-run') options.dryRun = true
    else if (flag === '--uninstall') options.uninstall = true
    else if (flag === '--no-copy') options.noCopy = true
    else if (flag === '--bundle') options.bundle = true
    else if (flag === '--help' || flag === '-h') options.help = true
    else if (flag === '--dsh-home') options.dshHome = value()
    else if (flag === '--profile') options.profiles.push(...String(value()).split(',').map(s => s.trim()).filter(Boolean))
    else if (flag === '--mode') options.mode = value()
    else if (flag === '--audit') options.mode = 'audit'
    else throw new Error('unknown argument: ' + arg)
  }
  if (options.mode !== 'enforce' && options.mode !== 'audit') throw new Error('--mode must be enforce or audit')
  return options
}

/** @param {string} value */
function expandHomePath(value) {
  if (value === '~') return homedir()
  if (value.startsWith('~/')) return join(homedir(), value.slice(2))
  return value
}

/** @param {string} text */
function stripManagedBlock(text) {
  let value = text
  const blocks = [
    [START, END],
    [OLD_START, OLD_END],
  ]
  for (const [start, end] of blocks) {
    const pattern = new RegExp('(?:^|\\n)' + escapeRegExp(start) + '[\\s\\S]*?' + escapeRegExp(end) + '[^\\n]*\\n?', 'g')
    value = value.replace(pattern, '\n')
  }
  return value
}

/** @param {string} value */
function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/** @param {string} text */
function normalizePatchText(text) {
  let value = stripManagedBlock(text).replace(/\n{3,}/g, '\n\n')
  if (/^\s*\[\s*\]\s*$/m.test(value)) value = value.replace(/^\s*\[\s*\]\s*$/m, '')
  return value.replace(/^\s*\n/, '')
}

/** @param {string} line */
function indentOf(line) {
  return line.match(/^\s*/)[0].length
}

/** @param {string} value */
function unquote(value) {
  const trimmed = value.trim()
  if ((trimmed.startsWith("'") && trimmed.endsWith("'")) || (trimmed.startsWith('"') && trimmed.endsWith('"'))) {
    return trimmed.slice(1, -1)
  }
  return trimmed
}

/**
 * @param {string} text
 * @param {string} rowId
 * @param {string} key
 * @returns {string | undefined}
 */
function rowValue(text, rowId, key) {
  const lines = text.split('\n')
  let found
  for (let i = 0; i < lines.length; i += 1) {
    const match = lines[i].match(/^(\s*)-\s+id:\s*['"]?([^'"\s#]+)['"]?\s*(?:#.*)?$/)
    if (!match || match[2] !== rowId) continue
    const rowIndent = match[1].length
    for (let j = i + 1; j < lines.length; j += 1) {
      const line = lines[j]
      if (line.trim().length === 0 || line.trim().startsWith('#')) continue
      const indent = indentOf(line)
      if (indent <= rowIndent && /^\s*-\s+/.test(line)) break
      if (indent <= rowIndent && /^\s*[A-Za-z0-9_-]+:/.test(line)) break
      const valueMatch = line.match(new RegExp('^\\s+' + key + ':\\s*(.*?)\\s*$'))
      if (valueMatch) found = unquote(valueMatch[1].replace(/\s+#.*$/, ''))
    }
  }
  return found
}

/**
 * @param {string} text
 * @param {string} provider
 * @returns {string | undefined}
 */
function providerBaseUrlFromYaml(text, provider) {
  const lines = text.split('\n')
  for (let i = 0; i < lines.length; i += 1) {
    if (!/^\s*providers:\s*(?:#.*)?$/.test(lines[i])) continue
    const providersIndent = indentOf(lines[i])
    for (let j = i + 1; j < lines.length; j += 1) {
      const line = lines[j]
      if (line.trim().length === 0 || line.trim().startsWith('#')) continue
      const indent = indentOf(line)
      if (indent <= providersIndent) break
      if (indent !== providersIndent + 2) continue
      const keyMatch = line.match(/^\s+(['"]?)([^'":]+)\1:\s*(.*)$/)
      if (!keyMatch || keyMatch[2].trim() !== provider) continue
      for (let k = j + 1; k < lines.length; k += 1) {
        const sub = lines[k]
        if (sub.trim().length === 0 || sub.trim().startsWith('#')) continue
        if (indentOf(sub) <= indent) break
        const baseMatch = sub.match(/^\s+baseURL:\s*(.*?)\s*(?:#.*)?$/)
        if (baseMatch) return unquote(baseMatch[1])
      }
    }
  }
  return undefined
}

/** @param {unknown} value @returns {string[]} */
function catalogBaseUrls(value) {
  if (typeof value !== 'object' || value === null) return []
  const urls = []
  const hosts = new Set()
  for (const api of Object.values(value)) {
    if (typeof api !== 'object' || api === null) continue
    for (const model of Object.values(api)) {
      if (typeof model !== 'object' || model === null || typeof model.baseUrl !== 'string') continue
      try {
        const url = new URL(model.baseUrl)
        if (hosts.has(url.host)) continue
        hosts.add(url.host)
        urls.push(model.baseUrl)
      } catch {
        // Skip one malformed optional catalog entry.
      }
    }
  }
  return urls
}

/**
 * @param {string} dshHome
 * @param {string} profileDir
 * @param {string} provider
 * @returns {string[]}
 */
function catalogBaseUrlsFor(dshHome, profileDir, provider) {
  const candidates = [
    join(dshHome, 'profiles', 'node_modules', '@earendil-works', 'pi-ai', 'dist', 'providers', 'data', provider + '.json'),
    join(profileDir, 'node_modules', '@earendil-works', 'pi-ai', 'dist', 'providers', 'data', provider + '.json'),
  ]
  for (const candidate of candidates) {
    if (!existsSync(candidate)) continue
    try {
      const urls = catalogBaseUrls(JSON.parse(readFileSync(candidate, 'utf8')))
      if (urls.length > 0) return urls
    } catch {
      // A corrupt optional catalog is not a reason to stop the install.
    }
  }
  return []
}

/**
 * @param {string} dshHome
 * @param {string} profileDir
 * @param {string} provider
 * @returns {string[]} normalized hostnames
 */
function resolveProviderHosts(dshHome, profileDir, provider) {
  const patchPath = join(profileDir, 'cordis.patch.yml')
  const patchText = existsSync(patchPath) ? readFileSync(patchPath, 'utf8') : ''
  const settingsPath = join(dshHome, 'settings.yaml')
  const settingsText = existsSync(settingsPath) ? readFileSync(settingsPath, 'utf8') : ''
  const urls = []
  const fromSettings = providerBaseUrlFromYaml(settingsText, provider)
  if (fromSettings !== undefined) urls.push(fromSettings)
  const fromPatch = providerBaseUrlFromYaml(patchText, provider)
  if (fromPatch !== undefined) urls.push(fromPatch)
  const deepseekBaseUrl = rowValue(patchText, 'llm-deepseek', 'baseURL')
  if (deepseekBaseUrl !== undefined && (provider === 'deepseek-official' || provider === 'deepseek')) urls.push(deepseekBaseUrl)
  urls.push(...catalogBaseUrlsFor(dshHome, profileDir, provider))
  urls.push(...(KNOWN_BASE_URLS[provider] ?? []))

  const hosts = []
  const seen = new Set()
  for (const url of urls) {
    try {
      const host = new URL(url).hostname.toLowerCase()
      if (host.length === 0 || seen.has(host)) continue
      seen.add(host)
      hosts.push(host)
    } catch {
      // Ignore one malformed optional URL.
    }
  }
  return hosts
}

/** @param {string[]} lines @param {string[]} values @param {string} key */
function yamlList(lines, values, key, indent = '          ') {
  lines.push('        ' + key + ':')
  for (const value of values) lines.push(indent + "- '" + String(value).replace(/'/g, "''") + "'")
}

/**
 * @param {object} input
 * @param {string} input.entryPath
 * @param {string | undefined} input.provider
 * @param {string | undefined} input.model
 * @param {string[]} input.hosts
 * @param {string} input.mode
 * @param {string} input.auditLog
 * @returns {string}
 */
function buildBlock(input) {
  const lines = [START, '# revision: ' + new Date().toISOString(), '- insert:', '    - id: provider-guard', "      name: '" + input.entryPath.replace(/'/g, "''") + "'", '      config:']
  lines.push('        followSelection: true')
  if (input.provider !== undefined) {
    lines.push("        fallbackProvider: '" + input.provider.replace(/'/g, "''") + "'")
    if (input.model !== undefined) lines.push("        fallbackModel: '" + input.model.replace(/'/g, "''") + "'")
  }
  lines.push("        onForeignProvider: 'block'")
  lines.push('        blockAutoSwitch: true')
  lines.push('        blockForeignProviderHosts: true')
  if (input.provider !== undefined && input.hosts.length > 0) {
    lines.push('        providerHosts:')
    lines.push("          '" + input.provider.replace(/'/g, "''") + "':")
    for (const host of input.hosts) lines.push("            - '" + host.replace(/'/g, "''") + "'")
  }
  lines.push("        mode: '" + input.mode + "'")
  lines.push("        auditLog: '" + input.auditLog.replace(/'/g, "''") + "'")
  lines.push('        logAllowed: false')
  lines.push(END)
  return lines.join('\n') + '\n'
}

/** @param {string} source @param {string} target */
function copyPlugin(source, target) {
  const temp = target + '.tmp-' + process.pid
  rmSync(temp, { recursive: true, force: true })
  cpSync(source, temp, {
    recursive: true,
    filter: (src) => {
      const name = src.split(/[\\/]/).pop() ?? ''
      return !['node_modules', '.git', 'test', '.DS_Store'].includes(name)
    },
  })
  rmSync(target, { recursive: true, force: true })
  renameSync(temp, target)
}

function printHelp() {
  console.log(`dsh-provider-guard installer

  node scripts/install.mjs                    show the plan (writes nothing)
  node scripts/install.mjs --apply            install into every profile
  node scripts/install.mjs --apply --mode audit
  node scripts/install.mjs --uninstall --apply

Options:
  --dsh-home PATH        default: \$DSH_HOME or ~/.dsh
  --profile NAME[,NAME]  default: every directory under profiles/ with cordis.yml
  --mode enforce|audit   default: enforce
  --bundle               reference the installed package name instead of copying into DSH_HOME
  --no-copy              reference the checkout path instead of copying into DSH_HOME
  --apply                write changes (without it the script is a dry run)
`)
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  if (options.help) {
    printHelp()
    return
  }
  const dshHome = resolve(expandHomePath(options.dshHome))
  const profilesRoot = join(dshHome, 'profiles')
  if (!existsSync(profilesRoot)) throw new Error('profiles directory not found: ' + profilesRoot)

  const available = readdirSync(profilesRoot, { withFileTypes: true })
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name)
    .filter(name => existsSync(join(profilesRoot, name, 'cordis.yml')) || existsSync(join(profilesRoot, name, 'package.json')))
    .sort()
  const selected = options.profiles.length > 0 ? options.profiles : available
  if (selected.length === 0) throw new Error('no DSH profiles found under ' + profilesRoot)

  let entryPath = options.bundle ? PACKAGE_NAME : join(ROOT, 'lib', 'index.js')
  let installedCopy
  if (!options.noCopy && !options.bundle) {
    const target = join(dshHome, 'plugins', PACKAGE_NAME)
    entryPath = join(target, 'lib', 'index.js')
    installedCopy = target
  }

  const plans = []
  for (const profile of selected) {
    const profileDir = join(profilesRoot, profile)
    if (!existsSync(profileDir)) {
      plans.push({ profile, error: 'profile directory not found: ' + profileDir })
      continue
    }
    const patchPath = join(profileDir, 'cordis.patch.yml')
    const existing = existsSync(patchPath) ? readFileSync(patchPath, 'utf8') : ''
    if (options.bundle && !existsSync(join(profileDir, 'node_modules', PACKAGE_NAME, 'package.json'))) {
      plans.push({ profile, error: PACKAGE_NAME + ' is not installed in this profile; run: dsh plugin --profile ' + profile + ' add ' + ROOT })
      continue
    }
    const normalizedExisting = normalizePatchText(existing)
    if (options.uninstall) {
      plans.push({ profile, patchPath, next: normalizedExisting, changed: normalizedExisting !== existing, action: 'remove' })
      continue
    }
    if (/^\s*-\s+id:\s*['"]?provider-guard['"]?\s*$/m.test(normalizedExisting)) {
      plans.push({ profile, error: 'profile already has a provider-guard row outside the managed block; remove it manually' })
      continue
    }
    const provider = rowValue(existing, 'agent-default-model', 'provider')
    const model = rowValue(existing, 'agent-default-model', 'model')
    const hosts = provider === undefined ? [] : resolveProviderHosts(dshHome, profileDir, provider)
    const auditLog = join(dshHome, 'provider-guard', 'audit-' + profile + '.jsonl')
    const block = buildBlock({
      entryPath,
      provider,
      model,
      hosts,
      mode: options.mode,
      auditLog,
    })
    const next = (normalizedExisting.trim().length === 0 ? '' : normalizedExisting.replace(/\s*$/, '\n\n')) + block
    plans.push({ profile, provider, model, hosts, patchPath, next, changed: next !== existing, action: 'install' })
  }

  const failures = plans.filter(plan => plan.error !== undefined)
  const changes = plans.filter(plan => plan.error === undefined && plan.changed)
  for (const plan of plans) {
    if (plan.error !== undefined) {
      console.log('[skip] ' + plan.profile + ': ' + plan.error)
      continue
    }
    if (plan.action === 'remove') {
      console.log('[plan] ' + plan.profile + ': remove managed block' + (plan.changed ? '' : ' (not installed)'))
      continue
    }
    console.log('[plan] ' + plan.profile + ': provider=' + (plan.provider ?? '(follow UI)')
      + (plan.model === undefined ? '' : ' model=' + plan.model)
      + ' hosts=' + (plan.hosts.length > 0 ? plan.hosts.join(',') : '(built-in)')
      + ' mode=' + options.mode)
  }

  if (!options.apply || options.dryRun) {
    console.log('\nDry run only. Re-run with --apply to write.')
    return
  }
  if (installedCopy !== undefined && !options.uninstall) {
    mkdirSync(dirname(installedCopy), { recursive: true })
    copyPlugin(ROOT, installedCopy)
    console.log('[copy] plugin -> ' + installedCopy)
  }
  for (const plan of changes) {
    writeFileSync(plan.patchPath, plan.next, 'utf8')
    console.log('[write] ' + plan.patchPath)
  }
  console.log('\n完成。桌面端通常热加载；web / VS Code 面板重启后生效。')
  console.log('验证：让 DSH 调用 provider_guard_status，或看 ' + join(dshHome, 'provider-guard', 'audit-<profile>.jsonl'))
  if (failures.length > 0) process.exitCode = 1
}

main()