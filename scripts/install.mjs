#!/usr/bin/env node
/**
 * Install dsh-provider-guard into every DSH profile on this machine.
 *
 * Desktop, `dsh web`, and the VS Code panel all load a profile from
 * `$DSH_HOME/profiles/<name>`; the VS Code panel starts the `web` profile by
 * default. The script detects the profile's current default provider/model,
 * resolves that provider's endpoint from settings, the profile patch, the
 * installed pi-ai catalog, or a small provider table, and writes a marked
 * patch row. It also removes the previous dsh-egress-guard block if present.
 *
 * Usage:
 *   node scripts/install.mjs                 # show the plan, write nothing
 *   node scripts/install.mjs --apply         # install into every profile
 *   node scripts/install.mjs --apply --mode audit
 *   node scripts/install.mjs --uninstall --apply
 *
 * @module dsh-provider-guard/install
 */

